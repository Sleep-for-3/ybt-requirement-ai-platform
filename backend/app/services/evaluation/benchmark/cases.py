"""Synthetic benchmark corpus: six families, seeded rewrites, explicit expectations.

Design rules enforced by :func:`app.services.evaluation.benchmark.dataset.validate_case`:

* every case is marked ``synthetic: True`` and carries ``provenance`` in
  ``{"synthetic", "synthetic_seeded"}`` -- no business row, no real regulatory text;
* rewrites of one scenario share ``seed_id`` so :func:`dataset.split_cases` can keep the
  whole group on one side of the dev/holdout boundary;
* ``expected`` states what the platform must produce (a status, a verdict tally, an
  ordering guarantee) and ``forbidden`` states what it must never produce, so a scoring
  rule cannot be tilted after seeing a holdout failure;
* ``source_type`` distinguishes material the platform may cite (knowledge units) from
  material it must reject (out-of-scope / archived / cross-project units).

The corpus is intentionally *not* generated from one template: each seed encodes a
different business mistake that the platform is expected to catch.
"""
from __future__ import annotations

from typing import Any

# --------------------------------------------------------------------------- builders


def _unit(unit_id: int, content: str, *, version: int = 1, **extra: Any) -> dict:
    """One synthetic knowledge unit. ``version`` stands in for its document version."""
    return {"knowledge_unit_id": unit_id, "content": content, "version": version,
            "confidentiality_level": "internal", "authority_rank": 5, **extra}


def _case(
    case_id: str,
    family: str,
    seed_id: str,
    query: str,
    evidence: list[dict],
    *,
    model_answer: str,
    model_claims: list[str] | None = None,
    judge: dict | None = None,
    expected: dict,
    forbidden: list[str],
    scoring: dict,
    source_type: str = "synthetic_regulation",
    notes: str = "",
    state_chain: dict | None = None,
) -> dict:
    case = {
        "case_id": case_id,
        "family": family,
        "seed_id": seed_id,
        "source_type": source_type,
        "query": query,
        "evidence": evidence,
        "model_answer": model_answer,
        "model_claims": list(model_claims or []),
        "judge": judge,
        "expected": expected,
        "forbidden": forbidden,
        "scoring": scoring,
        "provenance": "synthetic_seeded",
        "synthetic": True,
        "notes": notes,
    }
    if state_chain is not None:
        case["state_chain"] = state_chain
    return case


def _expected_status(**values: Any) -> dict:
    return {"answer_status": values.pop("answer_status", None),
            "confidence_not_above": values.pop("confidence_not_above", None),
            "citation_support": values.pop("citation_support", None),
            **values}


